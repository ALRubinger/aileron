#!/usr/bin/env node
// Reads ../tokens.json and emits ./output/tokens.generated.css.
// The output file defines all design tokens as CSS custom properties under :root
// and .dark, using shadcn-svelte's conventional names for semantic tokens so it
// drops into the existing @theme inline block in docs/ and webapp/.

import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = resolve(HERE, "..", "..");
const TOKENS_PATH = resolve(HERE, "..", "tokens.json");

// Three outputs from one source. The first is the reference copy for
// inspection. The others are imported by each stack's CSS entry.
const OUTPUTS = [
	resolve(HERE, "output", "tokens.generated.css"),
	resolve(REPO_ROOT, "docs", "src", "styles", "tokens.generated.css"),
	resolve(REPO_ROOT, "webapp", "src", "tokens.generated.css"),
];

const tokens = JSON.parse(readFileSync(TOKENS_PATH, "utf8"));

function getByPath(obj, path) {
	return path.split(".").reduce((acc, key) => acc?.[key], obj);
}

function resolveValue(value) {
	if (typeof value === "string") {
		return value.replace(/\{([^}]+)\}/g, (_, path) => {
			const node = getByPath(tokens, path);
			if (node == null) throw new Error(`Unresolved token reference: {${path}}`);
			const inner = node.$value ?? node;
			return resolveValue(inner);
		});
	}
	if (Array.isArray(value)) {
		return value.map((v) => (v.includes(" ") || v.includes(",") ? `"${v}"` : v)).join(", ");
	}
	return String(value);
}

function tokenValue(node) {
	if (node == null) return null;
	if (node.$value !== undefined) return resolveValue(node.$value);
	return null;
}

// DTCG groups can carry $description and other $-prefixed metadata. Iterate
// only the data keys when treating a group as a collection.
function entries(group) {
	return Object.entries(group).filter(([k]) => !k.startsWith("$"));
}

const lines = [];

function emit(line) {
	lines.push(line);
}

function emitBlock(selector, body) {
	emit(`${selector} {`);
	for (const [name, value] of body) {
		emit(`\t--${name}: ${value};`);
	}
	emit("}");
	emit("");
}

emit("/*");
emit(" * Generated by design/build/generate-tokens.mjs from design/tokens.json.");
emit(" * Do not edit by hand. Re-run the generator after changing tokens.json.");
emit(" */");
emit("");

// :root — light mode + mode-invariant tokens
const rootVars = [];

// color.brand
rootVars.push(["color-brand-black", tokenValue(tokens.color.brand.black)]);
rootVars.push(["color-brand-white", tokenValue(tokens.color.brand.white)]);
for (const [step, node] of entries(tokens.color.brand.gray)) {
	rootVars.push([`color-brand-gray-${step}`, tokenValue(node)]);
}

// color.status
for (const [name, group] of entries(tokens.color.status)) {
	rootVars.push([`color-status-${name}`, tokenValue(group.base)]);
	rootVars.push([`color-status-${name}-foreground`, tokenValue(group.foreground)]);
}

// color.mode.light → conventional shadcn names
for (const [name, node] of entries(tokens.color.mode.light)) {
	rootVars.push([name, tokenValue(node)]);
}

// typography
// Emit raw families under --font-family-* to avoid collision with the
// Tailwind utility name --font-sans. Each stack's @theme inline block
// maps --font-sans: var(--font-family-sans) to expose the utility.
rootVars.push(["font-family-sans", resolveValue(tokens.typography.family.sans.$value)]);
rootVars.push(["font-family-mono", resolveValue(tokens.typography.family.mono.$value)]);
rootVars.push(["font-weight-regular", tokenValue(tokens.typography.weight.regular)]);
rootVars.push(["font-weight-black", tokenValue(tokens.typography.weight.black)]);

// typography scale (flat: --text-{step}-{size|line-height|tracking})
for (const [step, group] of entries(tokens.typography.scale)) {
	rootVars.push([`text-${step}-size`, tokenValue(group.size)]);
	rootVars.push([`text-${step}-line-height`, tokenValue(group.lineHeight)]);
	rootVars.push([`text-${step}-tracking`, tokenValue(group.tracking)]);
}

// typography roles (composite: emit size, line-height, tracking, weight per role)
for (const [role, def] of entries(tokens.typography.role)) {
	const scaleStep = tokens.typography.scale[def.scale];
	rootVars.push([`role-${role}-size`, tokenValue(scaleStep.size)]);
	rootVars.push([`role-${role}-line-height`, tokenValue(scaleStep.lineHeight)]);
	rootVars.push([`role-${role}-tracking`, tokenValue(scaleStep.tracking)]);
	rootVars.push([`role-${role}-weight`, resolveValue(def.weight)]);
	rootVars.push([`role-${role}-family`, resolveValue(def.family)]);
}

// spacing rhythm
for (const [key, group] of entries(tokens.spacing.rhythm)) {
	if (group.$value !== undefined) {
		rootVars.push([`space-${key}`, tokenValue(group)]);
	} else {
		for (const [variant, node] of Object.entries(group)) {
			rootVars.push([`space-${key}-${variant}`, tokenValue(node)]);
		}
	}
}

// radius
rootVars.push(["radius", tokenValue(tokens.radius.base)]);
rootVars.push(["radius-sm", tokenValue(tokens.radius.sm)]);
rootVars.push(["radius-md", tokenValue(tokens.radius.md)]);
rootVars.push(["radius-lg", tokenValue(tokens.radius.lg)]);
rootVars.push(["radius-xl", tokenValue(tokens.radius.xl)]);
rootVars.push(["radius-full", tokenValue(tokens.radius.full)]);

// elevation
rootVars.push(["shadow-low", tokenValue(tokens.elevation.low)]);
rootVars.push(["shadow-mid", tokenValue(tokens.elevation.mid)]);
rootVars.push(["shadow-high", tokenValue(tokens.elevation.high)]);
rootVars.push(["shadow-focus", tokenValue(tokens.elevation.focus)]);

// motion
for (const [name, node] of entries(tokens.motion.duration)) {
	rootVars.push([`duration-${name}`, tokenValue(node)]);
}
for (const [name, node] of entries(tokens.motion.easing)) {
	const v = node.$value;
	rootVars.push([`easing-${name}`, `cubic-bezier(${v.join(", ")})`]);
}

// z
for (const [name, node] of entries(tokens.z)) {
	rootVars.push([`z-${name}`, tokenValue(node)]);
}

// pattern (background images, parallax rate, etc.)
for (const [name, node] of entries(tokens.pattern)) {
	rootVars.push([`pattern-${name}`, tokenValue(node)]);
}

// effect (composite filter / decoration values)
for (const [name, node] of entries(tokens.effect)) {
	rootVars.push([`effect-${name}`, tokenValue(node)]);
}

emitBlock(":root", rootVars);

// .dark — overrides for dark mode semantic tokens + dark ring focus shadow
const darkVars = [];
for (const [name, node] of entries(tokens.color.mode.dark)) {
	darkVars.push([name, tokenValue(node)]);
}
// Recompute the focus shadow using the dark ring value.
darkVars.push([
	"shadow-focus",
	`0 0 0 3px ${tokenValue(tokens.color.mode.dark.ring)}`,
]);
emitBlock(".dark", darkVars);

// Breakpoints are emitted as a comment block. Tailwind v4 reads them from
// @theme directives, not from CSS custom properties. The two stacks' @theme
// blocks should reference these values directly.
emit("/* Breakpoints (Tailwind @theme values, not CSS custom properties):");
for (const [name, node] of entries(tokens.breakpoint)) {
	emit(` *   --breakpoint-${name}: ${tokenValue(node)};`);
}
emit(" */");

const body = lines.join("\n");
for (const path of OUTPUTS) {
	mkdirSync(dirname(path), { recursive: true });
	writeFileSync(path, body, "utf8");
	console.log(`Wrote ${path}`);
}
console.log(`  ${rootVars.length} :root vars`);
console.log(`  ${darkVars.length} .dark vars`);
